q_num(doc, 10, 'Что такое закон Литтла и как он обосновывает результаты модели?')
answer_label(doc)
body(doc, 'Закон Литтла (1961) — фундаментальный результат теории очередей: L = λ × W, где L — среднее количество задач в системе, λ — средний поток (задач в единицу времени), W — среднее время нахождения задачи в системе (цикловое время).')
body(doc, 'Практическое следствие для Kanban: WIP-лимит удерживает L на постоянном уровне (не более 4 задач). Если поток λ не меняется, то W = L/λ автоматически снижается. Иными словами, ограничение числа одновременно выполняемых задач механически сокращает цикловое время — и именно это объясняет преимущество Kanban по Cycle Time.')
body(doc, 'В Scrum WIP явно не ограничен: все задачи спринта считаются в работе одновременно, L растёт, и по закону Литтла W увеличивается. Это фундаментальная причина, по которой Cycle Time Scrum выше Kanban при прочих равных условиях.')
sep(doc)

